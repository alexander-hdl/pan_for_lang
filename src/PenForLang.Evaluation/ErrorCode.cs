namespace PenForLang.Evaluation;

/// <summary>
/// Коды находок оценщика (ARCHITECTURE.md §6.2; таксономия методики §7.3). Стоповость кода по режиму и контексту
/// определяет <c>errors.json</c> (Learner, Lesson.Feedback), а не оценщик. Часть кодов в v0 не выдаётся:
/// они появятся с гипотезами (L), словами (J) и беглостью (K); перечисление совпадает с §6.2 заранее.
/// </summary>
public enum ErrorCode
{
    /// <summary>Межалфавитная подстановка (кириллица). В v0 не выдаётся.</summary>
    L1,

    /// <summary>Другая латинская буква. В v0 не выдаётся.</summary>
    L2,

    /// <summary>Подмена внутри моторной семьи. В v0 не выдаётся.</summary>
    L2m,

    /// <summary>Пропущенная буква. В v0 не выдаётся.</summary>
    L3,

    /// <summary>Лишняя буква. В v0 не выдаётся.</summary>
    L4,

    /// <summary>Ошибка в графеме. В v0 не выдаётся.</summary>
    L5,

    /// <summary>Ошибка гласной. В v0 не выдаётся.</summary>
    L5v,

    /// <summary>Знак транскрипции вместо буквы. В v0 не выдаётся.</summary>
    L6,

    /// <summary>Вариантное написание UK/US. В v0 не выдаётся.</summary>
    Var,

    /// <summary>Неверная точка старта штриха.</summary>
    P1,

    /// <summary>Обратное направление штриха.</summary>
    P2,

    /// <summary>Неверный порядок штрихов.</summary>
    P3,

    /// <summary>Лишний штрих основного следа (буква «кусками»).</summary>
    P4,

    /// <summary>Пропущенный штрих основного следа.</summary>
    P5,

    /// <summary>Ретрейс выполнен не по написанному (например, параллельной линией или петлёй).</summary>
    P6,

    /// <summary>Отрыв на месте соединения. В изолированной букве не выдаётся.</summary>
    J1,

    /// <summary>Высота соединения. В изолированной букве не выдаётся.</summary>
    J2,

    /// <summary>Вход в следующую букву. В изолированной букве не выдаётся.</summary>
    J3,

    /// <summary>Лишние углы и петли в соединении. В изолированной букве не выдаётся.</summary>
    J4,

    /// <summary>Общее отклонение формы.</summary>
    F1,

    /// <summary>Овал не замкнут.</summary>
    F2,

    /// <summary>Нет нужной петли.</summary>
    F3,

    /// <summary>Не достаёт линеек или выходит за них.</summary>
    F4,

    /// <summary>Посадка на базовую линию.</summary>
    F5,

    /// <summary>Наклон (в режиме <c>absolute</c>).</summary>
    F6,

    /// <summary>Размер. В изолированной букве не выдаётся (размер — это F4).</summary>
    F7,

    /// <summary>Интервалы. В изолированной букве не выдаётся.</summary>
    F8,

    /// <summary>Нет точки или перекладины.</summary>
    D1,

    /// <summary>Отложенный штрих не на месте.</summary>
    D2,

    /// <summary>Лишняя черта (лишний отложенный штрих).</summary>
    D3,

    /// <summary>Отложенный штрих поставлен сразу, а не после слова: информационная находка, не ошибка (решение заказчика).</summary>
    D4,

    /// <summary>Латентность. Группа K — этап беглости, в v0 не выдаётся.</summary>
    K1,

    /// <summary>Паузы. В v0 не выдаётся.</summary>
    K2,

    /// <summary>Инверсии скорости. В v0 не выдаётся.</summary>
    K3,

    /// <summary>Дорисовки. В v0 не выдаётся.</summary>
    K4,
}
